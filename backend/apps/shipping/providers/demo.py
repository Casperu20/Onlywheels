"""
Simulated courier for demos and coursework (SHIPPING_CARRIER=demo). Nothing leaves the server:
AWBs are random "DEMO…" numbers, the label is a generated one-page PDF, and every tracking refresh
moves the parcel one step (picked up → in transit → delivered). Refused by production settings.
"""

import secrets
from decimal import Decimal

from apps.orders.models import Order

from .base import AwbResult, CarrierProvider, TrackingUpdate

# Labels mimic Romanian carrier wording so they also pass `classify_carrier_status`.
_NEXT = {
    "created": TrackingUpdate(status="picked_up", label="Colet ridicat de curier (simulat)"),
    "picked_up": TrackingUpdate(status="in_transit", label="In tranzit (simulat)"),
    "in_transit": TrackingUpdate(status="delivered", label="Livrat (simulat)"),
}


def _pdf_text(value: str) -> str:
    ascii_only = value.encode("ascii", "replace").decode()
    return ascii_only.replace("\\", "\\\\").replace("(", "\\(").replace(")", "\\)")


def label_pdf(awb: str) -> bytes:
    lines = [
        (20, "OnlyWheels - DEMO COURIER"),
        (14, "SIMULATED LABEL - NOT A REAL SHIPMENT"),
        (28, f"AWB {awb}"),
        (11, "Generated by SHIPPING_CARRIER=demo for testing and presentations."),
    ]
    body = "".join(f"/F1 {size} Tf ({_pdf_text(line)}) Tj 0 -40 Td " for size, line in lines)
    stream = f"BT 60 760 Td {body}ET".encode()
    objects = [
        b"<< /Type /Catalog /Pages 2 0 R >>",
        b"<< /Type /Pages /Kids [3 0 R] /Count 1 >>",
        b"<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] "
        b"/Resources << /Font << /F1 5 0 R >> >> /Contents 4 0 R >>",
        b"<< /Length %d >>\nstream\n%s\nendstream" % (len(stream), stream),
        b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>",
    ]
    out = bytearray(b"%PDF-1.4\n")
    offsets = []
    for number, body in enumerate(objects, start=1):
        offsets.append(len(out))
        out += b"%d 0 obj\n%s\nendobj\n" % (number, body)
    xref = len(out)
    out += b"xref\n0 %d\n0000000000 65535 f \n" % (len(objects) + 1)
    out += b"".join(b"%010d 00000 n \n" % offset for offset in offsets)
    out += b"trailer\n<< /Size %d /Root 1 0 R >>\nstartxref\n%d\n%%%%EOF\n" % (len(objects) + 1, xref)
    return bytes(out)


class DemoProvider(CarrierProvider):
    name = "demo"
    display_name = "Demo courier (simulated)"

    def create_awb(self, order: Order, *, parcels: list[Decimal]) -> AwbResult:
        return AwbResult(awb=f"DEMO{secrets.randbelow(10**10):010d}", tracking_url="")

    def download_label(self, awb: str) -> bytes:
        return label_pdf(awb)

    def track(self, awb: str) -> TrackingUpdate:
        from apps.shipping.models import Shipment

        status = Shipment.objects.filter(carrier=self.name, awb=awb).values_list("status", flat=True).first()
        return _NEXT.get(status, TrackingUpdate(status=None, label=""))
